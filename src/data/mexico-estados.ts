/** Obtiene los municipios de un estado por su nombre */
export function getMunicipiosByEstado(nombreEstado: string): MunicipioMx[] {
  const estado = ESTADOS_MX.find(
    (e) => e.nombre.toLowerCase() === nombreEstado.toLowerCase()
  )
  return estado?.municipios ?? []
}

